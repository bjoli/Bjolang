"""Generates the grapheme tables of (std unicode grapheme) from the UCD.

Usage: gen_grapheme.py UCD_DIR

UCD_DIR holds, from https://www.unicode.org/Public/UCD/latest/ucd/:
  auxiliary/GraphemeBreakProperty.txt
  auxiliary/GraphemeBreakTest.txt
  emoji/emoji-data.txt
  DerivedCoreProperties.txt
(the files may also lie directly in UCD_DIR).

Writes:
  lib/std/unicode/grapheme-table.protobjo     the property table
  TestFiles/assets/unicode/grapheme-cases.protobjo  the conformance cases

The property of a code point is one byte:
  bits 0-3  Grapheme_Cluster_Break, numbered as GCB below
  bit  4    Extended_Pictographic
  bits 5-6  Indic_Conjunct_Break: 0 None, 1 Linker, 2 Consonant, 3 Extend

The table has two stages of 256-entry blocks: stage 1 maps `cp >> 8` to a
block, and stage 2 holds the blocks. Both are written as text: stage 1 as
two hex digits per block number, stage 2 as one character per entry, the
index of its property byte in a list of the bytes that occur, plus '0'.
"""

import os
import sys

GCB = ['Other', 'CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator',
       'Prepend', 'SpacingMark', 'L', 'V', 'T', 'LV', 'LVT']
INCB = {'Linker': 1, 'Consonant': 2, 'Extend': 3}
N = 0x110000
BLOCK = 256
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))


def find(ucd, sub, name):
    for p in (os.path.join(ucd, sub, name), os.path.join(ucd, name)):
        if os.path.exists(p):
            return p
    sys.exit(f'gen_grapheme.py: no {name} in {ucd}')


def version(path):
    with open(path, encoding='utf-8') as f:
        first = f.readline()
    # "# GraphemeBreakProperty-18.0.0.txt"
    return first.split('-')[-1].replace('.txt', '').strip()


def ranges(path):
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.split('#')[0].strip()
            if not line:
                continue
            fields = [x.strip() for x in line.split(';')]
            lo, _, hi = fields[0].partition('..')
            yield int(lo, 16), int(hi or lo, 16), fields[1:]


def wrap(text, width=100, indent='    '):
    return '\n'.join(indent + text[i:i + width] for i in range(0, len(text), width))


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    ucd = sys.argv[1]
    gbp = find(ucd, 'auxiliary', 'GraphemeBreakProperty.txt')
    gbt = find(ucd, 'auxiliary', 'GraphemeBreakTest.txt')
    emo = find(ucd, 'emoji', 'emoji-data.txt')
    dcp = find(ucd, '', 'DerivedCoreProperties.txt')
    ver = version(gbp)
    for p in (gbt, dcp):
        if version(p) != ver:
            sys.exit(f'gen_grapheme.py: {p} is version {version(p)}, not {ver}')

    props = [0] * N
    for lo, hi, f in ranges(gbp):
        g = GCB.index(f[0])
        for c in range(lo, hi + 1):
            props[c] |= g
    for lo, hi, f in ranges(emo):
        if f[0] == 'Extended_Pictographic':
            for c in range(lo, hi + 1):
                props[c] |= 1 << 4
    for lo, hi, f in ranges(dcp):
        if f[0] == 'InCB':
            for c in range(lo, hi + 1):
                props[c] |= INCB[f[1]] << 5

    kinds = sorted(set(props))
    assert len(kinds) <= 64, len(kinds)
    kind_of = {p: i for i, p in enumerate(kinds)}
    blocks, stage1 = {}, []
    for b in range(0, N, BLOCK):
        key = tuple(props[b:b + BLOCK])
        stage1.append(blocks.setdefault(key, len(blocks)))
    assert len(blocks) <= 256, len(blocks)
    stage2 = [p for block in sorted(blocks, key=blocks.get) for p in block]

    s1 = ''.join(f'{i:02x}' for i in stage1)
    s2 = ''.join(chr(ord('0') + kind_of[p]) for p in stage2)
    sk = ''.join(f'{p:02x}' for p in kinds)
    header = f''';; Generated by lib/std/unicode/gen_grapheme.py from the Unicode Character
;; Database {ver}: GraphemeBreakProperty.txt, emoji-data.txt and
;; DerivedCoreProperties.txt. Do not edit; run the script again instead.
;;
;; The data is © Unicode, Inc., under the Unicode License v3:
;; https://www.unicode.org/license.txt
'''
    table = header + f'''
;; The Unicode version the table is of.
(def unicode-version "{ver}")

;; Stage 1: the block of each 256 code points, as two hex digits.
(def stage1-text """
{wrap(s1)}
    """)

;; The property bytes that occur, as two hex digits each.
(def kinds-text "{sk}")

;; Stage 2: the blocks, one character per code point, the index of its
;; property byte in kinds-text plus '0'.
(def stage2-text """
{wrap(s2)}
    """)
'''
    out = os.path.join(ROOT, 'lib', 'std', 'unicode', 'grapheme-table.protobjo')
    with open(out, 'w', encoding='utf-8') as f:
        f.write(table)

    cases = []
    with open(gbt, encoding='utf-8') as f:
        for line in f:
            line = line.split('#')[0].strip()
            if line:
                cases.append(line.replace('÷', '/').replace('×', 'x'))
    test = header.replace('GraphemeBreakProperty.txt, emoji-data.txt and\n;; DerivedCoreProperties.txt',
                          'GraphemeBreakTest.txt') + f'''
;; The cases of GraphemeBreakTest.txt, one a line: code points in hex, with
;; "/" where a cluster boundary is and "x" where there is none.
(def grapheme-cases-version "{ver}")
(def grapheme-cases """
{chr(10).join('    ' + c for c in cases)}
    """)
'''
    os.makedirs(os.path.join(ROOT, 'TestFiles', 'assets', 'unicode'), exist_ok=True)
    out2 = os.path.join(ROOT, 'TestFiles', 'assets', 'unicode', 'grapheme-cases.protobjo')
    with open(out2, 'w', encoding='utf-8') as f:
        f.write(test)
    print(f'Unicode {ver}: {len(kinds)} property bytes, {len(blocks)} blocks, {len(cases)} cases')


if __name__ == '__main__':
    main()
