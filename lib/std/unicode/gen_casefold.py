"""Generates the case folding table of (std unicode casefold) from the UCD.

Usage: gen_casefold.py UCD_DIR

UCD_DIR holds CaseFolding.txt, from
https://www.unicode.org/Public/UCD/latest/ucd/.

Writes:
  lib/std/unicode/casefold-table.protobjo     the mappings
  TestFiles/assets/unicode/casefold-cases.protobjo  the same mappings, for the test

The table is the full case folding: the lines of status C and F. The lines
of status S (the simple alternatives to F) and T (the Turkic mappings of I
and İ) are left out.

Each mapping is written as fixed-width hex: the code point in 6 digits, the
number of code points it folds to in 1 digit, and each of those in 6 digits.
The mappings are in code point order, so the module can binary search them.
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))


def find(ucd, name):
    p = os.path.join(ucd, name)
    if not os.path.exists(p):
        sys.exit(f'gen_casefold.py: no {name} in {ucd}')
    return p


def version(path):
    with open(path, encoding='utf-8') as f:
        first = f.readline()
    # "# CaseFolding-18.0.0.txt"
    return first.split('-')[-1].replace('.txt', '').strip()


def mappings(path):
    out = []
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.split('#')[0].strip()
            if not line:
                continue
            code, status, target = [x.strip() for x in line.split(';')[:3]]
            if status in ('C', 'F'):
                out.append((int(code, 16), [int(t, 16) for t in target.split()]))
    out.sort()
    keys = [k for k, _ in out]
    assert len(keys) == len(set(keys)), 'a code point has both a C and an F line'
    assert all(1 <= len(t) <= 9 for _, t in out)
    return out


def wrap(text, width=100, indent='    '):
    return '\n'.join(indent + text[i:i + width] for i in range(0, len(text), width))


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    cf = find(sys.argv[1], 'CaseFolding.txt')
    ver = version(cf)
    ms = mappings(cf)
    text = ''.join(f'{k:06x}{len(t)}' + ''.join(f'{c:06x}' for c in t) for k, t in ms)
    header = f''';; Generated by lib/std/unicode/gen_casefold.py from the Unicode Character
;; Database {ver}: CaseFolding.txt. Do not edit; run the script again instead.
;;
;; The data is © Unicode, Inc., under the Unicode License v3:
;; https://www.unicode.org/license.txt
'''
    table = header + f'''
;; The Unicode version the table is of.
(def unicode-version "{ver}")

;; The number of mappings.
(def fold-count {len(ms)})

;; The full case folding, the lines of status C and F, in code point order.
;; Each mapping is the code point in 6 hex digits, the number of code points
;; it folds to in 1 digit, and each of those in 6 hex digits.
(def fold-text """
{wrap(text)}
    """)
'''
    out = os.path.join(ROOT, 'lib', 'std', 'unicode', 'casefold-table.protobjo')
    with open(out, 'w', encoding='utf-8') as f:
        f.write(table)

    cases = '\n'.join('    ' + f'{k:04X}; ' + ' '.join(f'{c:04X}' for c in t) for k, t in ms)
    test = header + f'''
;; The mappings of the table, one a line: a code point and what it folds
;; to, in hex.
(def casefold-cases-version "{ver}")
(def casefold-cases """
{cases}
    """)
'''
    os.makedirs(os.path.join(ROOT, 'TestFiles', 'assets', 'unicode'), exist_ok=True)
    out2 = os.path.join(ROOT, 'TestFiles', 'assets', 'unicode', 'casefold-cases.protobjo')
    with open(out2, 'w', encoding='utf-8') as f:
        f.write(test)
    full = sum(1 for _, t in ms if len(t) > 1)
    print(f'Unicode {ver}: {len(ms)} mappings, {full} of them to more than one code point')


if __name__ == '__main__':
    main()
